/**
 * 制作物IDからプレビュー専用説明文を取得します。
 *
 * 空欄の場合は空文字を返し、
 * modal-preview.js 側で description にフォールバックします。
 *
 * @param {*} publicationId
 * @returns {string}
 */
export function getPreviewDescription(
    publicationId
) {
    const normalizedId =
        String(
            publicationId ?? ""
        ).trim();

    if (!normalizedId) {
        return "";
    }

    const item =
        PREVIEW_DESCRIPTIONS.find(
            (entry) => {
                return (
                    String(
                        entry.id ?? ""
                    ).trim() ===
                    normalizedId
                );
            }
        );

    return String(
        item?.previewDescription ?? ""
    ).trim();
}

